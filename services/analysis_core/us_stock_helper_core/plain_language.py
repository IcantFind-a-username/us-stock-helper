def _direction_key(direction: Direction) -> str:
    if direction is Direction.BULLISH:
        return "bullish"
    if direction is Direction.BEARISH:
        return "bearish"
    raise ValueError(f"magic nine: unsupported direction: {direction!r}")


def _count_bucket(count: int) -> str:
    if 1 <= count <= 3:
        return "early"
    if 4 <= count <= 6:
        return "mid"
    if 7 <= count <= 8:
        return "late"
    raise ValueError(f"magic nine: unexpected in-progress count: {count!r}")


