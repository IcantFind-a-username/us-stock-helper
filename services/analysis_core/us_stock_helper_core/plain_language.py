def classify_rvol(result: RelativeVolumeResult) -> str:
    """Map an ``RelativeVolumeResult`` to one of ``RVOL_READINGS``'s keys.

    Raises ``ValueError`` if the result's ``missing_reason`` does not match
    any of the four reasons ``time_of_day_relative_volume`` actually emits --
    a new unavailable reason introduced there must add copy here, not fall
    through to a guess.
    """

    if result.quality_status == "unavailable":
        reason = result.missing_reason or ""
        if reason.startswith("no completed bars"):
            return "rvol-unavailable-no-data"
        if reason.startswith("early session"):
            return "rvol-unavailable-early-session"
        if reason.startswith("insufficient history"):
            return "rvol-unavailable-insufficient-history"
        if reason.startswith("historical baseline has no volume"):
            return "rvol-unavailable-zero-baseline"
        raise ValueError(f"rvol: unrecognized unavailable reason: {reason!r}")
    assert result.ratio is not None
    ratio = result.ratio
    if ratio < _RVOL_LIGHT_MAX:
        return "rvol-light"
    if ratio < _RVOL_NORMAL_MAX:
        return "rvol-normal"
    if ratio < _RVOL_MODERATE_HIGH_MAX:
        return "rvol-moderate-high"
    return "rvol-heavy"


def rvol_reading(result: RelativeVolumeResult) -> PlainReading:
    return RVOL_READINGS[classify_rvol(result)]


