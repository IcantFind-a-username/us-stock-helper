def classify_breadth(result: PercentAboveMAResult) -> str:
    if result.quality_status == "unavailable":
        return "breadth-unavailable"
    assert result.percent_above is not None
    percent_above = result.percent_above
    if percent_above >= _BREADTH_STRONG_MIN:
        return "breadth-strong"
    if percent_above <= _BREADTH_WEAK_MAX:
        return "breadth-weak"
    return "breadth-mixed"


