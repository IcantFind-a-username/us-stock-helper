"""Fixed, versioned plain-language readings for the quant surfaces.

Franz is a quant-finance novice. Every number this package computes has to
answer, in plain Chinese: 这是什么 / 现在说明什么 / 什么情况下这个判断作废
(docs/superpowers/plans/2026-08-15-quant-foundations-plain-language.md). This
module is the reviewed vocabulary that answers the first two questions; the
third (失效条件) is assembled by the caller alongside the actual served
numbers, because it is honest, already-typed data (sample sizes, thresholds,
missing reasons) that belongs with the result, not with static prose.

Three-layer contract (the plan's own words):
  1. 一句话白话结论 -- ``PlainReading.headline``. Varies by *state*.
  2. 展开解释 -- ``PlainReading.explanation``. What the indicator measures,
     with a lived-world analogy. Fixed *per indicator* (not per state) --
     every state of one indicator shares the same explanation text, because
     the mechanism does not change, only the current reading does.
  3. 数字层 -- value, sample size, 失效条件. Never stored here; it comes from
     the actual result object (``RelativeVolumeResult.ratio``,
     ``VolatilityEstimate.sample_size``, ...), which the caller already has.

白话不喊单: no reading generated by this module may contain an instruction to
act. ``PlainReading.__post_init__`` enforces this at *construction* time --
not just in a test -- so a banned verb anywhere in a shipped headline or
explanation breaks the import of this module (and therefore the whole
``us_stock_helper_core`` package), rather than shipping quietly.

Completeness: every ``classify_*`` function maps its result type to a state
key drawn from a finite, explicitly enumerated domain (ratio buckets, count
buckets, direction, perfected...). A value outside that documented domain
raises ``ValueError`` -- classification never guesses and never falls back
to jargon. Every state a ``classify_*`` function can produce has a
``PlainReading`` in the matching ``*_READINGS`` dict (or, for Magic Nine's
per-count headline, a template rendered by its own ``*_reading`` function);
``tests/test_plain_language.py`` exercises every state in that domain against
the real classify function and asserts a reading comes back, so a new state
introduced without copy fails that test (and, for the banned-verb guard,
fails at import time regardless of whether a test ever runs).

Per-symbol wiring note (RVOL / range volatility): as of this module's
introduction, ``rvol.py`` and the ``parkinson``/``garman_klass`` estimators
in ``volatility.py`` are not yet part of any per-symbol wire payload --
that wiring is a separate, later task (see the plan's Task 5/6 split). This
module's ``RVOL_READINGS`` and ``VOLATILITY_READINGS`` exist and are fully
tested now specifically so that later wiring task only has to classify a
served result and look up a reading, never author copy under time pressure.
"""

