def classify_magic_nine_last_completed(last: MagicNineSignal | None) -> str:
    """State of the most recently completed run, carried separately on the
    wire as ``lastCompleted`` so it stays visible after counting restarts."""

    if last is None:
        return "magic-nine-last-completed-none"
    direction = _direction_key(last.direction)
    if last.perfected is True:
        return f"magic-nine-last-completed-{direction}-perfected"
    if last.perfected is False:
        return f"magic-nine-last-completed-{direction}-unperfected"
    return f"magic-nine-last-completed-{direction}-unknown"


def magic_nine_last_completed_reading(last: MagicNineSignal | None) -> PlainReading:
    return _MAGIC_NINE_LAST_COMPLETED_READINGS[
        classify_magic_nine_last_completed(last)
    ]
