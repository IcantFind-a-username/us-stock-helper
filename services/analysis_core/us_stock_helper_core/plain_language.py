# 白话不喊单: a generated reading may describe what an indicator measures and
# its current state; it may never instruct an action. Enforced in
# PlainReading.__post_init__, not only in a test.
BANNED_VERBS: tuple[str, ...] = ("买入", "卖出", "加仓", "抄底", "梭哈")


@dataclass(frozen=True, slots=True)
class PlainReading:
    """Layers 1-2 of the three-layer contract: headline + explanation."""

    headline: str
    explanation: str

    def __post_init__(self) -> None:
        if not self.headline.strip():
            raise ValueError("a plain-language reading requires a headline")
        if not self.explanation.strip():
            raise ValueError("a plain-language reading requires an explanation")
        for verb in BANNED_VERBS:
            if verb in self.headline:
                raise ValueError(
                    f"plain-language headline must never contain {verb!r}: "
                    f"{self.headline!r}"
                )
            if verb in self.explanation:
                raise ValueError(
                    f"plain-language explanation must never contain {verb!r}: "
                    f"{self.explanation!r}"
                )


