_VOLATILITY_ESTIMATORS: tuple[str, ...] = ("close_to_close", "parkinson", "garman_klass")

_VOLATILITY_LOW_MAX = 0.15
_VOLATILITY_NORMAL_MAX = 0.30
_VOLATILITY_ELEVATED_MAX = 0.50

_VOLATILITY_BUCKET_HEADLINES: dict[str, str] = {
    "low": "最近这段时间的价格波动幅度偏低，走势相对平稳。",
    "normal": "最近这段时间的价格波动幅度处于正常区间。",
    "elevated": "最近这段时间的价格波动幅度温和偏高，起伏比平时明显一些。",
    "high": "最近这段时间的价格波动幅度明显偏高，起伏比平时大很多。",
    "unavailable-insufficient-sample": "波动率暂不可用：已收盘的K线数量还不够计算。",
    "unavailable-flat": (
        "波动率暂不可用：这段窗口里价格完全没有波动，无法算出有意义的数值。"
    ),
}

_VOLATILITY_EXPLANATIONS: dict[str, str] = {
    "close_to_close": (
        "这个估算只看每根K线的收盘价，和上一根收盘价之间的变化幅度——就像只记录"
        "你每天下班时体重秤上的数字，不管中间一天里怎么波动。方法简单、最常用，"
        "但看不到同一根K线内部走了多远。"
    ),
    "parkinson": (
        "这个估算看的是每根K线自己的最高价和最低价之间的距离——就像不只记体重，"
        "还记录你一天里最重和最轻的两个时刻差多少。比只看收盘价更能捕捉盘中波动，"
        "但假设价格不会跳空、不会带着趋势走。"
    ),
    "garman_klass": (
        "这个估算综合了每根K线的最高、最低、开盘和收盘价——在最高最低的基础上，"
        "再看开盘到收盘的净移动。信息更全，但同样假设没有跳空、没有隔夜跳动。"
    ),
}

VOLATILITY_READINGS: dict[str, PlainReading] = {
    f"volatility-{estimator}-{bucket}": PlainReading(
        headline=headline, explanation=_VOLATILITY_EXPLANATIONS[estimator]
    )
    for estimator in _VOLATILITY_ESTIMATORS
    for bucket, headline in _VOLATILITY_BUCKET_HEADLINES.items()
}


def classify_volatility(estimate: VolatilityEstimate) -> str:
    """Map a ``VolatilityEstimate`` to one of ``VOLATILITY_READINGS``'s keys."""

    estimator = estimate.estimator
    if estimator not in _VOLATILITY_ESTIMATORS:
        raise ValueError(f"volatility: unrecognized estimator: {estimator!r}")
    if estimate.quality_status == "unavailable":
        reason = estimate.missing_reason or ""
        if reason.startswith("insufficient sample"):
            return f"volatility-{estimator}-unavailable-insufficient-sample"
        if reason == "no price variation in the observed window":
            return f"volatility-{estimator}-unavailable-flat"
        raise ValueError(f"volatility: unrecognized unavailable reason: {reason!r}")
    assert estimate.value is not None
    value = estimate.value
    if value < _VOLATILITY_LOW_MAX:
        bucket = "low"
    elif value < _VOLATILITY_NORMAL_MAX:
        bucket = "normal"
    elif value < _VOLATILITY_ELEVATED_MAX:
        bucket = "elevated"
    else:
        bucket = "high"
    return f"volatility-{estimator}-{bucket}"


def volatility_reading(estimate: VolatilityEstimate) -> PlainReading:
    return VOLATILITY_READINGS[classify_volatility(estimate)]


