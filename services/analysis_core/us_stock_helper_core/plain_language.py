def classify_magic_nine_progress(setup: TDSetupResult | None) -> str:
    """State of the run in progress right now (what the chart badge shows).

    ``setup`` is ``None`` when the count could not be computed at all (no
    bars); a computed ``setup`` whose ``latest`` is ``None`` is a genuine
    "no run in progress right now" answer, not the same as unavailable --
    mirrors the wire's own ``qualityStatus`` discipline (snapshot.py).
    """

    if setup is None:
        return "magic-nine-unavailable"
    signal = setup.latest
    if signal is None:
        return "magic-nine-no-active-run"
    direction = _direction_key(signal.direction)
    if not signal.completed:
        return f"magic-nine-{direction}-{_count_bucket(signal.count)}"
    if signal.perfected is True:
        return f"magic-nine-{direction}-complete-perfected"
    if signal.perfected is False:
        return f"magic-nine-{direction}-complete-unperfected"
    return f"magic-nine-{direction}-complete-unknown"


def magic_nine_progress_reading(setup: TDSetupResult | None) -> PlainReading:
    state = classify_magic_nine_progress(setup)
    template = _MAGIC_NINE_PROGRESS_HEADLINE_TEMPLATES[state]
    count = (
        setup.latest.count
        if setup is not None and setup.latest is not None
        else None
    )
    headline = template.format(count=count) if count is not None else template
    return PlainReading(headline=headline, explanation=_MAGIC_NINE_EXPLANATION)


